// Generates api/_lib/kb.js — knowledge chunks with precomputed embeddings.
// Run locally with: npm run embed  (requires GEMINI_API_KEY in .env)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { CHUNKS } from "./knowledge-content.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

// minimal .env loader
for (const line of fs.existsSync(path.join(root, ".env"))
  ? fs.readFileSync(path.join(root, ".env"), "utf8").split(/\r?\n/)
  : []) {
  const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/);
  if (m && !(m[1] in process.env)) process.env[m[1]] = m[2];
}

const API_KEY = process.env.GEMINI_API_KEY;
if (!API_KEY) {
  console.error("GEMINI_API_KEY not set");
  process.exit(1);
}

const EMBED_MODEL = "gemini-embedding-001";
const DIM = 768;

async function embed(text, taskType) {
  const res = await fetch(
    `https://generativelanguage.googleapis.com/v1beta/models/${EMBED_MODEL}:embedContent`,
    {
      method: "POST",
      headers: { "Content-Type": "application/json", "X-goog-api-key": API_KEY },
      body: JSON.stringify({
        content: { parts: [{ text }] },
        taskType,
        outputDimensionality: DIM,
      }),
    }
  );
  if (!res.ok) throw new Error(`Embed failed ${res.status}: ${await res.text()}`);
  const data = await res.json();
  // Truncated-dimension embeddings must be re-normalized for cosine similarity.
  const v = data.embedding.values;
  const norm = Math.sqrt(v.reduce((s, x) => s + x * x, 0));
  return v.map((x) => +(x / norm).toFixed(6));
}

const out = [];
for (const chunk of CHUNKS) {
  process.stdout.write(`embedding ${chunk.id}... `);
  const vector = await embed(chunk.text, "RETRIEVAL_DOCUMENT");
  out.push({ ...chunk, vector });
  console.log("ok");
}

const libDir = path.join(root, "api", "_lib");
fs.mkdirSync(libDir, { recursive: true });
fs.writeFileSync(
  path.join(libDir, "kb.js"),
  `// AUTO-GENERATED by scripts/build-embeddings.mjs — do not edit by hand.\n` +
    `export const EMBED_MODEL = ${JSON.stringify(EMBED_MODEL)};\n` +
    `export const EMBED_DIM = ${DIM};\n` +
    `export const KB = ${JSON.stringify(out)};\n`
);
console.log(`wrote api/_lib/kb.js with ${out.length} chunks`);
